'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ctx={window:{},console};
vm.runInNewContext(fs.readFileSync('assets/hit-reporters.js','utf8'),ctx);
const {match,load}=ctx.window.OchaPHitReporters;
const actual={order:[1,2,3]};
const forecast={
  ocha:{main:['1-2-3'],reverse:['2-1-3'],navi:['1-2-3','1-2-4']},
  gemi:{main:['1-3-2'],reverse:['3-1-2'],navi:['1-2-3']}
};
let hit=match(actual,forecast);
assert.deepEqual(Array.from(hit[0].groups),['本線','舟券ナビ']);
assert.deepEqual(Array.from(hit[1].groups),['舟券ナビ']);
hit=match({order:[2,1,3]},forecast);
assert.equal(hit[0].groups[0],'逆張り');
assert.equal(hit[1].known,true);assert.equal(hit[1].groups.length,0);
hit=match(actual,{gemi:forecast.gemi});
assert.equal(hit[0].known,false);assert.equal(hit[0].groups.length,0);
assert.equal(hit[1].groups[0],'舟券ナビ');
assert.equal(match({order:[1,1,3]},forecast).length,0);
assert.equal(match({order:[1,2,7]},forecast).length,0);
assert.equal(match(actual,{ocha:{main:['1-1-3']}})[0].known,false);
ctx.window.__OCHAP_SELECTED_DATE__='2026-11-04';
load('2026-11-03').then(x=>assert.equal(x,null));
console.log('PASS: reporter-specific hits, both reporters, overlapping categories, misses, unknown inputs and date isolation');

const score=ctx.window.OchaPHitReporters.score;
const row={venue_code:10,race_no:1,order:[1,2,3],trifecta_payout_yen:2000,exacta_payout_yen:500,refund_boats:[]};
const forecasts={'v10-r1':forecast};
let s=score([row],forecasts,'ocha');
assert.equal(s.n,1);assert.equal(s.one,1);assert.equal(s.two,1);assert.equal(s.three,1);
assert.equal(s.stake,400);assert.equal(s.payout,4000);assert.equal(s.profit,3600);assert.equal(s.roi,1000);
s=score([row,row],forecasts,'ocha');
assert.equal(s.n,1);assert.equal(s.stake,400,'duplicate results do not double investment');
s=score([row],forecasts,'ocha','navi');
assert.equal(s.n,1);assert.equal(s.stake,200);assert.equal(s.payout,2000);
s=score([row],forecasts,'gemi');
assert.equal(s.stake,300);assert.equal(s.payout,2000);
s=score([row],forecasts,'absent');assert.equal(s.n,0);assert.equal(s.roi,null);
s=score([{...row,order:undefined}],forecasts,'ocha');assert.equal(s.n,0);
s=score([{...row,order:[1,1,3]}],forecasts,'ocha');assert.equal(s.n,0);
s=score([{...row,order:[1,2,4],refund_boats:[3]}],forecasts,'ocha');
assert.equal(s.refund,300);assert.equal(s.payout,2300);assert.equal(s.stake,400);
s=score([{...row,refund_boats:undefined}],forecasts,'ocha');assert.equal(s.refundUnknown,1);
s=score([row],forecasts,'ocha','all','two');
assert.equal(s.stake,300,'2連単 deduplicates prefixes within each group only');
assert.equal(s.payout,1000,'same winning prefix across main/navi is two purchases');
s=score([{...row,exacta_payout_yen:undefined}],forecasts,'ocha','all','two');
assert.equal(s.missingPayout,1);assert.equal(s.financeN,0);assert.equal(s.roi,null);
assert.equal(s.totalStake,300,'investment stays known even when winning payout is missing');
s=score([{...row,order:[6,5,4],exacta_payout_yen:undefined}],forecasts,'ocha','all','two');
assert.equal(s.financeN,1);assert.equal(s.payout,0,'missing winning price does not block an observed miss');
s=score([row],{'v10-r1':{ocha:{main:['1-2-3'],reverse:[],navi:[]}}},'ocha','navi');
assert.equal(s.n,0,'a navi pass is not a losing prediction');
console.log('PASS: category denominators, three/two ticket finance, cross-category overlap, refunds, missing payouts and duplicate races');
